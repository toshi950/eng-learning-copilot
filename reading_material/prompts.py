"""確定プロンプト（フェーズ1: 長文読解教材生成）

チャット画面での検証（2026-08-15）を経て確定し、2026-08-16にMarkdown出力向けの
見出し構造・改行を調整。同日、内部設計メモのPhase 1定義（背景知識作成／
スラッシュリーディング／構文解説／直訳）に合わせて背景知識セクションを追加。
背景・設計判断は内部設計メモ（GitHub_LinkedInポートフォリオ戦略.md）を参照。
"""

READING_MATERIAL_PROMPT_TEMPLATE = """\
あなたは英語学習者向けの読解教材を作成する専門家です。
以下の英文を、指定のフォーマットで分析してください。出力はそのままMarkdownファイルとして
保存されるため、Markdownとして正しく整形すること。

【入力する英文】
{text}

【出力ルール】

1. 出力は必ず以下の3セクション構成のみとし、それ以外の前置き・後書き・補足コメントは一切出力しないこと。
   各見出しは `##` で始まるMarkdown見出しとし、見出しの直後は1行空けること。

## 背景知識

## Chunk Reading

## 構文読解・意味解析テーブル

2. 「背景知識」セクションは、この英文を読むにあたって読者が事前に知っておくと理解の助けになる
   背景知識を、日本語の箇条書き（3〜6項目程度）でまとめる。
   - 固有名詞・専門用語・組織名などには英語表記を併記する（例：SEC（米国証券取引委員会））。
   - 記事本文の内容そのものの要約はしない（それは本文を読めば分かるため）。あくまで読解の前提となる
     背景知識・文脈情報に絞る。
   - 平易な日本語で、簡潔に記述する。

3. 「Chunk Reading」セクションは、原文を意味・構文のまとまり（チャンク）ごとに " / " で区切って再掲する。
   - 1チャンクの目安は2〜7語程度。息継ぎ・聴解の単位（呼吸区切り）として不自然にならない長さにする。
   - 主語(S)、動詞句(V)、目的語(O)、補語(C)、修飾語句(M)、接続詞＋節など、統語上の境界で区切る。
   - 語順・文の分割は変更せず、原文をそのまま使うこと（要約・言い換えをしない）。

4. 「構文読解・意味解析テーブル」セクションは、Markdownの表として出力し、以下の列を必ずこの順序で含めること。

   | チャンク (Chunk) | 役割/文法構造 | 直訳・意味の塊 | 読解・聴解のポイント |

   - 行数は、3のChunk Readingで区切ったチャンクの数と完全に一致させること（1行=1チャンク）。
   - 「チャンク (Chunk)」列：該当チャンクの原文をそのまま記載。
   - 「役割/文法構造」列：S/V/O/C/Mなどの文成分表記に加え、時制・態・句/節の種類を簡潔に併記する
     （例：「動詞句 (V: 進行形受動態)」「前置詞句 (M: 目的・場所)」「接続詞 + 動名詞主語 (S)」など）。
   - 「直訳・意味の塊」列：そのチャンク単体の意味を、頭から読み下す順序のまま日本語化する。
     文全体を自然な日本語に意訳し直すのではなく、あくまで「そのチャンクを読んだ瞬間に脳内に浮かぶ意味の単位」を示すこと。
   - 「読解・聴解のポイント」列：なぜそこで区切れるか、前後のチャンクとの意味的つながり、
     逆接・因果などのディスコースマーカーの働き、リスニング時の注意点（弱形・リンキング等）を
     一言で簡潔に説明する。

5. 全体を通じて説明文は日本語、英文（Chunk Readingおよびテーブルの原文セル）はそのまま英語で出力すること。

6. 文法用語は日本の英語学習者に馴染みのある表記（S/V/O/C/M、不定詞、動名詞、分詞構文、
   関係代名詞節、前置詞句など）を優先して使うこと。
"""


def build_prompt(text: str) -> str:
    """英語長文テキストを埋め込んだプロンプト文字列を返す。"""
    return READING_MATERIAL_PROMPT_TEMPLATE.format(text=text)
