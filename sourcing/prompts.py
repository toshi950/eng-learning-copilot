"""フェーズ3「専門分野の情報収集」のプロンプト定義。

RSSフィードから収集済みの記事候補一覧（`feeds.collect_candidates`）を渡し、
その中からトピックを1つ選ばせたうえで、
(1) 実務者向けの日本語リサーチレポート と (2) 読み上げ・学習用の英語記事抜粋
の両方を生成させる。

探索的な検索はRSS側で肩代わり済みのため、モデルに許可するWeb検索・取得は
「選んだトピックの裏取りと本文取得」に限った少数回のみ。詳細な設計判断は
内部設計メモ（GitHub_LinkedInポートフォリオ戦略.md「フェーズ3」）を参照。
"""
from __future__ import annotations

PERSONA_DOMAINS = """\
- 会計監査・保険会計監査（IFRS、ディスクロージャー等）
- 内部統制・内部監査（COSO、SOX対応、監査DX）
- 会計・経理・税務実務（日本の会計基準・税制、経理DX含む）
- 監査領域における生成AI・自動化（AI Agent、LLM活用、RPA、監査データアナリティクス）
- ITガバナンス・情報セキュリティ監査（CISA領域）
- Alteryx/Python/SQL等を用いたデータ分析・EUC開発の実務トレンド"""


def build_prompt(candidates_text: str) -> str:
    """RSSで収集した候補一覧を踏まえたプロンプトを組み立てる。"""
    return f"""あなたは、公認会計士（日本）・CISA取得者としての専門性を持つ監査・会計データ
アナリティクス実務者向けに、専門分野の一次情報を調査するリサーチャーです。

【専門分野】
{PERSONA_DOMAINS}

【RSSで収集した記事候補】
以下は、専門分野に関連するRSSフィードから自動収集した直近の記事候補です。

{candidates_text}

【タスク】
上記の候補の中から、専門分野の実務者にとって最も価値のあるトピックを1つ選び、
以下の2つの成果物を作成してください。

候補の選定方針：
- 単発の人事・イベント告知・製品PR・地域ニュースではなく、基準・規制の動向や
  実務への影響を論じられるトピックを優先する
- 候補の見出しが手がかりとして弱い場合は、関連する重要トピックとして扱える
  ものを選んでよい
- 候補一覧に適切なものが1つもない場合に限り、専門分野の中で現時点でも実務上
  参照される重要トピックを自分で選んでよい

裏取りと本文取得：
選んだトピックについて、Web検索・Web取得ツールを使って内容を確認してください。
ただし探索は既にRSS側で済んでいるため、**ツールの利用は合計5回程度までに
抑えること**（選んだ記事の本文取得と、必要最小限の裏取りのみ）。網羅的な調査は
不要です。

1. 日本語リサーチレポート（research_report_ja）
   選んだトピックについて、確認できた内容を踏まえ、実務者として読み応えのある
   分量（目安2,000〜4,000字程度）でMarkdown形式のレポートを作成する。見出し（##）
   で内容を構造化し、参照した情報源は文末に箇条書きでリンク付きで列挙すること。
   推測で補わず、確認できた事実のみを記載すること。

2. 読み上げ・学習用の英語記事抜粋（english_text）
   1のトピックに関連する、信頼できる英語媒体の記事から200〜600語程度を
   抜粋・整形する。原文の表現は変更しないこと（要約・言い換えをしない）。
   これは私個人の英語学習（音読・リスニング練習）のためだけに使うものであり、
   第三者への配布・公開・商用利用は一切行わない。この個人利用の前提のもと、
   出典を明記した上で原文を引用してよい。可能であれば、IFRS Foundation・
   PCAOB・ASBJ等の公的な基準設定主体やBig4系Insightsページなど、比較的
   自由に引用・共有しやすい情報源を優先すると良い。
   日本語のトピックを選んだ場合でも、この抜粋は必ず英語の情報源から作ること
   （英語学習が目的のため）。関連する英語記事が見つからない場合は、同じ論点を
   扱う国際的な基準設定主体・Big4等の英語資料を使ってよい。

【出力ルール】
出力は以下のJSON構造のみとし、前置き・後書きは一切出力しないこと。

{{
  "topic_title": "扱うトピックの見出し（日本語）",
  "research_report_ja": "上記1の日本語リサーチレポート（Markdown）",
  "article_title": "抜粋元の記事タイトル（原文英語）",
  "article_source_url": "抜粋元の記事URL",
  "article_source_name": "抜粋元の媒体名",
  "article_published_date": "YYYY-MM-DD（不明な場合は空文字）",
  "english_text": "上記2の英語記事抜粋"
}}
"""
