"""フェーズ3「専門分野の情報収集」のプロンプト定義。

RSSフィードから収集済みの記事候補一覧（`feeds.collect_candidates`）を渡し、
その中から専門分野の記事を1件選ばせ、本文を取得して、読み上げ・学習用の
英語抜粋（200〜600語）を出典情報つきで返させる。

日本語のリサーチレポート生成は当初この工程に含めていたが、出力トークンが
コストの大半を占めるうえ、フォーマットの厳密さが不要な用途であることから、
API側からは削除しClaude Code CLIの定期実行に分離した（2026-08-31）。
本モジュールは英語記事の供給に専念する。

探索的な検索はRSS側で肩代わり済みのため、モデルに許可するWeb検索・取得は
「選んだ記事の特定と本文取得」に限った少数回のみ。
"""
from __future__ import annotations

PERSONA_DOMAINS = """\
- 会計監査・保険会計監査（IFRS、ディスクロージャー等）
- 内部統制・内部監査（COSO、SOX対応、監査DX）
- 会計・経理・税務実務
- 監査領域における生成AI・自動化（AI Agent、LLM活用、RPA、監査データアナリティクス）
- ITガバナンス・情報セキュリティ監査（CISA領域）"""


def build_prompt(candidates_text: str) -> str:
    """RSSで収集した候補一覧を踏まえたプロンプトを組み立てる。"""
    return f"""あなたは、公認会計士（日本）・CISA取得者である私の英語学習用に、専門分野の
英語記事を選定・整形するアシスタントです。

【私の専門分野】
{PERSONA_DOMAINS}

【RSSで収集した記事候補】
以下は、専門分野に関連するGoogle News RSSから自動収集した直近の記事候補です。
各行の末尾にある媒体名が、その記事の掲載元ドメインです。

{candidates_text}

【タスク】
上記の候補から、専門分野の実務者にとって最も読む価値のある英語記事を1件選び、
その本文を取得して、読み上げ・音読練習用の抜粋を作成してください。

選定方針：
- 単発の人事・イベント告知・製品PR・地域ニュースではなく、基準・規制の動向や
  実務への影響を扱う記事を優先する
- 英語の記事であること（日本語記事は選ばない）
- 候補に適切なものがない場合に限り、専門分野で現在参照価値のある英語記事を
  自分で探して選んでよい

本文の取得：
候補一覧のURLはGoogle Newsの転送URLで直接取得できないことがあります。その場合は
記事タイトルと媒体ドメインを手がかりに、Web検索・Web取得ツールで元記事を特定して
ください。**ツールの利用は合計5回程度までに抑えること。** 網羅的な調査は不要です。
有料記事等で本文が取得できない場合は、候補一覧の別の記事に切り替えてください。

抜粋の作成：
- 本文から連続する200〜600語程度を抜き出す
- **原文の表現を変更しないこと**（要約・言い換え・要点整理をしない）
- 文の途中で切らず、必ず文の区切りで終えること
- 見出し・著者名・広告・ナビゲーション等の本文以外の要素は含めないこと
- これは私個人の英語学習（音読・リスニング練習）のためだけに使うものであり、
  第三者への配布・公開・商用利用は一切行わない。この個人利用の前提のもと、
  出典を明記した上で原文を引用してよい

【出力ルール】
出力は以下のJSON構造のみとし、前置き・後書きは一切出力しないこと。

{{
  "article_title": "記事タイトル（原文英語）",
  "article_source_url": "元記事のURL（Google Newsの転送URLではなく、特定できた実URL）",
  "article_source_name": "媒体名",
  "article_published_date": "YYYY-MM-DD（不明な場合は空文字）",
  "topic_summary_ja": "この記事が何を扱っているかの1〜2文の日本語要約（読む前の手がかり用）",
  "english_text": "上記の英語抜粋"
}}
"""
